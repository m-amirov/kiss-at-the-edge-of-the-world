import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'config/music-cues.json'), 'utf8'));
const map = Object.fromEntries(config.cues.flatMap(cue => cue.sceneIds.map(sceneId => [sceneId, cue.cueId])));
if (Object.keys(map).length !== new Set(Object.keys(map)).size) throw new Error('duplicate scene mapping');
const source = `// GENERATED by tools/audio-generation/build-music-cues.mjs. Do not edit.\n` +
  `export const musicCues = ${JSON.stringify(config.cues, null, 2)};\n` +
  `export const musicCueBySceneId = ${JSON.stringify(map, null, 2)};\n` +
  `export function musicCueForScene(sceneId) { return musicCueBySceneId[sceneId] ?? 'main-theme'; }\n`;
fs.writeFileSync(path.join(root, 'src/music-cues.js'), source);
console.log(`generated ${config.cues.length} cues and ${Object.keys(map).length} scene mappings`);
