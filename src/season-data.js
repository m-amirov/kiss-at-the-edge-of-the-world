export const initialState = ({ provisional = false } = {}) => ({ nodeId: 'ep1-intro', lineIndex: 0, routeIntent: null, careerThesis: null, boundaries: 0, repairDebt: 0, commitment: false, trust: { eric: 0, nick: 0, damir: 0 }, flags: [], ending: null, visitedEpisodes: [1], ...(provisional ? createProvisionalMetadata() : createStateMetadata()), schemaVersion: SAVE_SCHEMA_VERSION });

export function canChoose(choice, state) {
  if (!choice.requires) return true;
  return Object.entries(choice.requires).every(([key, expected]) => key === 'routeIntent'
    ? state.routeIntent === expected
    : key === 'flag'
      ? state.flags.includes(expected)
      : key === 'flagsAll'
        ? expected.every(flag => state.flags.includes(flag))
        : key === 'flagsAny'
          ? expected.some(flag => state.flags.includes(flag))
          : state[key] === expected);
}

export function applyEffect(state, effect = {}) {
  if (effect.routeIntent !== undefined) state.routeIntent = effect.routeIntent;
  if (effect.careerThesis) state.careerThesis = effect.careerThesis;
  if (effect.boundaries) state.boundaries += effect.boundaries;
  if (effect.repairDebt) state.repairDebt = Math.max(0, state.repairDebt + effect.repairDebt);
  if (effect.commitment !== undefined) state.commitment = effect.commitment;
  if (effect.trust) Object.entries(effect.trust).forEach(([key, value]) => { state.trust[key] += value; });
  if (effect.flags) effect.flags.forEach(flag => { if (!state.flags.includes(flag)) state.flags.push(flag); });
}

export function resolveEnding(state) {
  const route = state.routeIntent;
  const routeRepair = route && `${route}-conflict-repaired`;
  if (route && route !== 'none' && state.commitment && state.flags.includes('concrete-plan') && state.flags.includes(routeRepair) && state.trust[route] >= 3 && state.boundaries >= 2 && state.repairDebt === 0) return `ending-${route}`;
  return 'ending-alice';
}
